/** Fills the development database with the same demo data the frontend preview mode shows ([[DemoDataSet]]).
  *
  * Run it with `sbt --client "backendMain/runMain com.togger.maintenance.DemoSeedApp"` against a migrated development
  * database. It syncs the `ai_endpoints` first, like the backend does on start. The demo accounts log in with the
  * credentials of [[DemoIdentity]]; accounts whose preview password is too weak for the backend get the admin
  * password. Ids of accounts, organizations, projects, labels and statuses are generated by the database, all other
  * rows keep the ids of the demo data. The default templates of a project are replaced by the demo ones for the same label. The app refuses to run twice: it stops when the demo admin account exists.
  */
object DemoSeedApp extends IOApp with SeedAppModule {

  private val projectLabelCategoryRepo = new ProjectLabelCategoryRepoImpl
  private val projectLabelRepo = new ProjectLabelRepoImpl
  private val milestoneDateRepo = new MilestoneDateRepoImpl
  private val milestoneDateVersionRepo = new MilestoneDateVersionRepoImpl
  private val milestoneSummaryRepo = new MilestoneSummaryRepoImpl
  private val milestoneSummaryVersionRepo = new MilestoneSummaryVersionRepoImpl
  private val promptTemplateRepo = new TgPromptTemplateRepoImpl
  private val promptTemplateVersionRepo = new TgPromptTemplateVersionRepoImpl
  private val aiActionRepo = new TgAiActionRepoImpl
  private val aiActionEndpointRepo = new TgAiActionEndpointRepoImpl
  private val aiActionDefaultRepo = new TgAiActionDefaultRepoImpl
  private val timeboxRepo = new TimeboxRepoImpl
  private val timeboxVersionRepo = new TimeboxVersionRepoImpl
  private val exportConfigRepo = new DataExportConfigRepoImpl
  private val importConfigRepo = new DataImportConfigRepoImpl
  private val projectMappingRepo = new ProjectMappingRepoImpl

  /** Demo id -> id in the database, for the rows whose id the database generates. */
  private type IdMap = Map[UUID, UUID]

  override def run(args: List[String]): IO[ExitCode] =
    for {
      alreadySeeded <- accountExists(DemoIdentity.AdminEmail).transact(xa)
      code <- if (alreadySeeded) refuse else seed.as(ExitCode.Success)
    } yield code

  private def refuse: IO[ExitCode] =
    IO.println(s"${DemoIdentity.AdminEmail} already exists, the demo data is not seeded again.").as(ExitCode.Error)

  private def accountExists(email: String): ConnectionIO[Boolean] =
    sql"select exists (select 1 from account where email = $email)".query[Boolean].unique

  private def seed: IO[Unit] = {
    val demo = DemoDataSet.build(now.atZone(ZoneOffset.UTC).toLocalDate, now)
    for {
      _ <- new AiEndpointSeedService(xa).run
      accountIds <- seedAccounts(demo.accounts)
      organizationIds <- seedOrganizations(demo.organizations, accountIds)
      projectLabelIds <- seedProjectLabels(demo).transact(xa)
      projectIds <- seedProjects(demo.projects, organizationIds, accountIds, projectLabelIds)
      statusAndLabelIds <- resolveTaskConfig(demo, projectIds)
      (statusIds, taskLabelIds) = statusAndLabelIds
      ids = Ids(accountIds, projectIds, statusIds, taskLabelIds)
      _ <- seedRest(demo, ids).transact(xa)
      _ <- IO.println(
        s"Seeded ${demo.accounts.size} accounts, ${demo.projects.size} projects, ${demo.milestones.size} milestones, " +
          s"${demo.tasks.size} tasks and ${demo.tasks.map(_.logEntries.size).sum} log entries."
      )
    } yield ()
  }

  private case class Ids(accounts: IdMap, projects: IdMap, statuses: IdMap, taskLabels: IdMap) {
    def account(id: UUID): UUID = accounts(id)
    def project(id: UUID): UUID = projects(id)
    def status(id: UUID): UUID = statuses(id)
    def taskLabel(id: UUID): UUID = taskLabels(id)
  }

  private def ensureAccountType(name: String): ConnectionIO[AccountType] =
    accountTypeRepo.findByName(name).attempt.flatMap {
      case Right(accountType) => accountType.pure[ConnectionIO]
      case Left(_) =>
        accountTypeRepo.insert(AccountType(id = UUID.randomUUID(), name = name, createdAt = now, updatedAt = now))
    }

  private def passwordOf(account: DemoAccount): HashedPassword =
    HashedPasswordImpl.fromPassword(
      Password.fromString(account.password).orElse(Password.fromString(DemoIdentity.AdminPassword)).toOption.get
    )

  private def seedAccounts(accounts: List[DemoAccount]): IO[IdMap] =
    for {
      adminType <- ensureAccountType(AdminCheck.AdminAccountTypeName).transact(xa)
      memberType <- ensureAccountType("developer").transact(xa)
      created <- accounts.traverse { account =>
        accountService
          .createAccount(
            Account(
              id = TgIds.UNASSIGNED_UUID,
              firstName = account.firstName,
              lastName = account.lastName,
              email = account.email,
              password = passwordOf(account),
              accountTypeId = if (account.admin) adminType.id else memberType.id,
              verified = true,
              enabled = true,
              createdAt = now,
              updatedAt = now
            )
          )
          .map(account.id -> _.id)
      }
    } yield created.toMap

  private def seedOrganizations(organizations: List[DemoOrganization], accountIds: IdMap): IO[IdMap] =
    organizations.traverse { organization =>
      val members = organization.memberIds.map(accountIds)
      organizationService
        .saveOrganization(
          Organization(TgIds.UNASSIGNED_UUID, organization.name, organization.description, organization.icon, now, now),
          members.head,
          members.tail
        )
        .map(organization.id -> _._1.id)
    }.map(_.toMap)

  private def seedProjectLabels(demo: DemoDataSet): ConnectionIO[IdMap] =
    for {
      categories <- demo.projectLabelCategories.traverse { category =>
        projectLabelCategoryRepo
          .insert(ProjectLabelCategory(TgIds.UNASSIGNED_UUID, category.name, now, now))
          .map(category.id -> _.id)
      }
      categoryIds = categories.toMap
      labels <- demo.projectLabels.traverse { label =>
        projectLabelRepo
          .insert(ProjectLabel(TgIds.UNASSIGNED_UUID, label.name, label.description, categoryIds(label.categoryId), now, now))
          .map(label.id -> _.id)
      }
    } yield labels.toMap

  private def seedProjects(
    projects: List[DemoProject],
    organizationIds: IdMap,
    accountIds: IdMap,
    projectLabelIds: IdMap
  ): IO[IdMap] =
    projects.traverse { project =>
      val members = project.memberIds.map(accountIds)
      projectService
        .saveProject(
          Project(
            id = TgIds.UNASSIGNED_UUID,
            organizationId = organizationIds(project.organizationId),
            name = project.name,
            description = project.description,
            icon = project.icon,
            workDays = project.workDays.map(DayOfWeek.of),
            createdAt = now,
            updatedAt = now
          ),
          members.head,
          members.tail,
          project.projectLabelIds.map(projectLabelIds)
        )
        .map(project.id -> _._1.id)
    }.map(_.toMap)

  /** `saveProject` creates the default statuses and labels; maps the demo ones onto them by name. */
  private def resolveTaskConfig(demo: DemoDataSet, projectIds: IdMap): IO[(IdMap, IdMap)] =
    (for {
      statuses <- demo.projects.flatTraverse { project =>
        TgPages.readAll(taskStatusRepo.findPaginatedByProjectId(projectIds(project.id), _)).map { dbStatuses =>
          demo.taskStatuses.filter(_.projectId == project.id).flatMap { status =>
            dbStatuses.find(_.name == status.status.statusName).map(status.id -> _.id)
          }
        }
      }
      labels <- demo.projects.flatTraverse { project =>
        TgPages.readAll(taskLabelRepo.findPaginatedByProjectId(projectIds(project.id), _)).map { dbLabels =>
          demo.taskLabels.filter(_.projectId == project.id).flatMap { label =>
            dbLabels.find(_.name == label.label.labelName).map(label.id -> _.id)
          }
        }
      }
    } yield (statuses.toMap, labels.toMap)).transact(xa)

  private def seedRest(demo: DemoDataSet, ids: Ids): ConnectionIO[Unit] =
    for {
      _ <- demo.taskTemplates.traverse_(seedTaskTemplate(_, ids))
      _ <- demo.milestones.traverse_(seedMilestone(_, ids))
      _ <- demo.promptTemplates.traverse_(seedPromptTemplate(_, ids))
      _ <- demo.aiActions.traverse_(seedAiAction(_, ids))
      _ <- demo.aiActionDefaults.traverse_(seedAiActionDefault(_, ids))
      _ <- demo.tasks.traverse_(seedTask(_, ids))
      _ <- demo.timeboxes.traverse_(seedTimebox(_, ids))
      _ <- demo.exportConfigs.traverse_(seedExportConfig(_, ids))
      _ <- demo.importConfigs.traverse_(seedImportConfig(_, ids))
      _ <- demo.projectMappings.traverse_(seedProjectMapping(_, ids))
    } yield ()

  private def seedTaskTemplate(template: DemoTaskTemplate, ids: Ids): ConnectionIO[Unit] =
    for {
      _ <- template.taskLabelId.map(ids.taskLabel).traverse_(dropDefaultTemplateOf)
      _ <- taskTemplateRepo.insertWithId(
        TaskTemplate(
          template.id,
          ids.project(template.projectId),
          template.taskLabelId.map(ids.taskLabel),
          ids.account(template.createdBy),
          template.createdAt
        )
      )
      _ <- template.versions.traverse_ { v =>
        taskTemplateVersionRepo.insertWithId(TaskTemplateVersion(v.id, template.id, v.name, v.body, v.createdAt))
      }
    } yield ()

  /** A label has at most one template and `saveProject` already created the default one. */
  private def dropDefaultTemplateOf(taskLabelId: UUID): ConnectionIO[Unit] =
    taskTemplateRepo.findByLabelId(taskLabelId).flatMap(_.traverse_(t => taskTemplateRepo.deleteById(t.id)))

  private def seedMilestone(m: DemoMilestone, ids: Ids): ConnectionIO[Unit] =
    for {
      _ <- milestoneRepo.insertWithId(Milestone(m.id, ids.project(m.projectId), m.createdAt))
      _ <- milestoneVersionRepo.insertWithId(
        MilestoneVersion(
          m.version,
          m.id,
          m.name,
          m.description,
          m.status,
          m.startDate,
          m.dueDate,
          m.endDate,
          m.createdAt,
          m.updatedAt
        )
      )
      _ <- m.dates.traverse_ { d =>
        milestoneDateRepo.insertWithId(MilestoneDate(d.id, m.id, d.createdAt)) *>
          milestoneDateVersionRepo.insertWithId(
            MilestoneDateVersion(d.version, d.id, d.name, d.description, d.date, d.updatedAt, d.updatedAt)
          )
      }
      _ <- m.summaries.traverse_ { s =>
        milestoneSummaryRepo.insertWithId(MilestoneSummary(s.id, m.id, s.createdAt)) *>
          milestoneSummaryVersionRepo.insertWithId(
            MilestoneSummaryVersion(s.version, s.id, s.text, s.fromDate, s.toDate, s.createdAt, s.updatedAt)
          )
      }
    } yield ()

  private def seedPromptTemplate(prompt: DemoPromptTemplate, ids: Ids): ConnectionIO[Unit] =
    promptTemplateRepo.insertWithId(TgPromptTemplate(prompt.id, ids.account(prompt.createdBy), prompt.createdAt)) *>
      prompt.versions.traverse_ { v =>
        promptTemplateVersionRepo.insertWithId(
          TgPromptTemplateVersion(v.version, v.tgPromptTemplateId, v.title, v.prompt, v.createdAt)
        )
      }

  private def seedAiAction(action: DemoAiAction, ids: Ids): ConnectionIO[Unit] =
    aiActionRepo.insertWithId(
      TgAiAction(
        action.id,
        ids.account(action.createdBy),
        action.name,
        action.prompt,
        action.promptTemplateId,
        action.model,
        action.createdAt,
        action.updatedAt
      )
    ) *> aiActionEndpointRepo.replaceBindings(action.id, action.endpoints.map(_.value))

  private def seedAiActionDefault(default: DemoAiActionDefault, ids: Ids): ConnectionIO[Unit] =
    aiActionDefaultRepo
      .upsert(
        TgAiActionDefault(
          ids.account(default.accountId),
          ids.project(default.projectId),
          default.endpoint.value,
          default.actionId
        )
      )
      .void

  private def seedTask(task: DemoTask, ids: Ids): ConnectionIO[Unit] =
    for {
      _ <- taskRepo.insertWithId(Task(task.id, ids.project(task.projectId), ids.account(task.createdBy), task.createdAt, task.archived))
      _ <- task.versions.traverse_ { v =>
        taskVersionRepo.insertWithId(
          TaskVersion(
            version = v.version,
            taskId = v.taskId,
            name = v.name,
            description = v.description,
            assignedTo = v.assignedTo.map(ids.account),
            closedBy = v.closedBy.map(ids.account),
            taskStatusId = ids.status(v.taskStatusId),
            priority = v.priority,
            milestone = v.milestone,
            startDate = v.startDate,
            dueDate = v.dueDate,
            endDate = v.endDate,
            createdAt = v.createdAt,
            updatedAt = v.updatedAt
          )
        )
      }
      _ <- task.labelIds.traverse_ { labelId =>
        taskLabelAssignmentRepo.insert(TaskLabelAssignment(task.id, ids.taskLabel(labelId), task.createdAt))
      }
      _ <- task.links.traverse_ { link =>
        linkRepo.insertWithId(Link(link.id, task.id, link.createdAt)) *>
          link.versions.traverse_ { v =>
            linkVersionRepo.insertWithId(LinkVersion(v.version, v.linkId, v.name, v.url, v.createdAt, v.updatedAt))
          }
      }
      _ <- task.logEntries.traverse_ { entry =>
        logEntryRepo.insertWithId(LogEntry(entry.id, task.id, ids.account(entry.createdBy), entry.createdAt)) *>
          entry.versions.traverse_ { v =>
            logEntryVersionRepo.insertWithId(
              LogEntryVersion(
                v.version,
                v.logEntryId,
                v.textInternal,
                v.textExternal,
                v.status,
                ids.account(v.createdBy),
                v.createdAt,
                v.updatedAt
              )
            )
          }
      }
    } yield ()

  private def seedTimebox(timebox: DemoTimebox, ids: Ids): ConnectionIO[Unit] =
    timeboxRepo.insertWithId(Timebox(timebox.id, ids.project(timebox.projectId), timebox.createdAt)) *>
      timebox.versions.traverse_ { v =>
        timeboxVersionRepo.insertWithId(
          TimeboxVersion(v.version, timebox.id, v.startDate, v.endDate, v.description, v.createdAt, v.changeComment)
        ) *> timeboxVersionRepo.insertPlannedTasks(v.version, v.taskVersionIds)
      }

  private def seedExportConfig(config: com.togger.dto.dataexportconfig.DataExportConfigResp, ids: Ids): ConnectionIO[Unit] =
    exportConfigRepo
      .insert(
        DataExportConfig(
          TgIds.UNASSIGNED_UUID,
          ids.project(config.projectId),
          ids.account(config.accountId),
          config.name,
          config.exportPath,
          config.createdAt,
          config.updatedAt
        )
      )
      .void

  private def seedImportConfig(config: com.togger.dto.dataimportconfig.DataImportConfigResp, ids: Ids): ConnectionIO[Unit] =
    importConfigRepo
      .insert(
        DataImportConfig(
          TgIds.UNASSIGNED_UUID,
          config.name,
          config.importPath,
          ids.project(config.projectId),
          ids.account(config.accountId),
          config.createdAt,
          config.updatedAt
        )
      )
      .void

  private def seedProjectMapping(mapping: DemoProjectMapping, ids: Ids): ConnectionIO[Unit] =
    projectMappingRepo
      .insert(
        ProjectMapping(
          ids.project(mapping.mapping.projectIdDb),
          mapping.mapping.projectIdDump,
          mapping.mapping.createdAt,
          mapping.mapping.updatedAt
        )
      )
      .void
}
