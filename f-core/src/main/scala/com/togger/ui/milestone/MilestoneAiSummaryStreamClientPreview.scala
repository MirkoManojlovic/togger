package com.togger.ui.milestone

import cats.effect.IO
import cats.implicits._
import com.togger.dto.SummariseMilestoneWithAiReq
import com.togger.preview._

import scala.concurrent.duration._

/** Writes a fake markdown summary of the milestone and its tasks (see [[TaskStatsSource]]) a few words at a time. */
class MilestoneAiSummaryStreamClientPreview(
  ctx: PreviewContext,
  projects: ProjectsPreviewData,
  data: MilestonesPreviewData,
  stats: TaskStatsPreviewData,
  chunkDelay: FiniteDuration = 60.millis
) extends MilestoneAiSummaryStreamClient {
  import AiSummaryEvent._

  private val ChunkPattern = """\S+\s*""".r

  override def stream(dto: SummariseMilestoneWithAiReq)(onEvent: AiSummaryEvent => Unit): IO[Unit] =
    ctx.loginRepo.account match {
      case None => IO(onEvent(Failed("Please log in again")))
      case Some(account) =>
        data.milestones.find(dto.milestoneId) match {
          case None => IO(onEvent(Failed("The AI could not summarise this period, the milestone was not found")))
          case Some(milestone) if !projects.isMember(milestone.projectId, account.id) =>
            IO(onEvent(Failed("You are not a member of this project")))
          case Some(_) if dto.endDate.isBefore(dto.startDate) =>
            IO(onEvent(Failed("The AI could not summarise this period, check the dates")))
          case Some(milestone) =>
            val activity = stats.source.activityOf(milestone.id, dto.startDate, dto.endDate)
            val words = ChunkPattern.findAllIn(markdown(milestone, dto, activity)).toList.grouped(2).map(_.mkString).toList
            words.traverse_(chunk => IO.sleep(chunkDelay) *> IO(onEvent(Chunk(chunk)))) *> IO(onEvent(Done))
        }
    }

  private def markdown(milestone: PreviewMilestone, dto: SummariseMilestoneWithAiReq, activity: List[MilestoneActivity]): String = {
    val header =
      s"## ${milestone.name}: ${dto.startDate} to ${dto.endDate}\n\n" +
        s"This period moved **${milestone.name}** forward. The milestone is currently *${milestone.status.statusName.toLowerCase}* " +
        s"and due on ${milestone.dueDate}.\n\n"
    val body =
      if (activity.isEmpty)
        "### Highlights\n\n- The team kept a steady pace and closed the planned work.\n" +
          "- Open items were reviewed and re-prioritised during the weekly sync.\n" +
          "- No blockers were reported.\n\n### Next steps\n\n- Finish the remaining tasks before the due date.\n"
      else
        "### Highlights\n\n" + activity.map(item => s"- **${item.taskName}** (${item.statusName})${logSuffix(item)}").mkString("\n") +
          "\n\n### Next steps\n\n- Close the tasks that are still open before the due date.\n"
    header + body + s"\n_Generated by ${dto.model} (preview mode, no AI was called)._\n"
  }

  private def logSuffix(item: MilestoneActivity): String =
    item.logTexts.headOption.fold("")(text => s": ${text.take(140)}")
}
